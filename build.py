def sign(n):
    return f"+{n}" if n >= 0 else f"&minus;{abs(n)}"


def render_pick(ch, p):
    cls = ["pick"]
    attrs = [f'data-pick="{p["id"]}"']
    if ch.get("choice"):
        cls.append("pick--choice")
        attrs.append(f'data-group="{ch["choice"]["group"]}"')
    if "taint_max" in p:
        cls.append("pick--gated")
        attrs.append(f'data-taint-max="{p["taint_max"]}"')
    out = [f'<div class="{" ".join(cls)}" {" ".join(attrs)}>']
    out.append(f'<h3>{p["name"]}</h3>')
    out.append(f'<p>{p["text"]}</p>')
    if p.get("price"):
        out.append(f'<span class="price">{p["price"]}</span>')
    if p.get("test"):
        out.append(f'<span class="test">{p["test"]}</span>')
    out.append('<span class="pick-state" aria-hidden="true"></span>')
    out.append("</div>")
    return "\n        ".join(out)


def render_ability(ch, a):
    attrs = [f'data-abil="{a["id"]}"', f'data-slot="{a["slot"]}"']
    if a["uses"]:
        attrs.append(f'data-uses="{a["uses"]}"')
        attrs.append(f'data-reset="{a["reset"]}"')
    if a.get("special"):
        attrs.append(f'data-special="{a["special"]}"')
    out = [f'<div class="abil" {" ".join(attrs)}>']
    out.append(f'<h3>{a["name"]}</h3>')
    out.append('<div class="row">')
    out.append(f'<span class="slot {a["slot"]}">{SLOT_LABEL[a["slot"]]}</span>')
    if a["uses"]:
        word = "за бой" if a["reset"] == "battle" else "в день"
        boxes = "".join("<i></i>" for _ in range(a["uses"]))
        times = "раз" if a["uses"] == 1 else "раза"
        out.append(f'<span class="uses" data-word="{word}">{boxes}'
                   f'<em>{a["uses"]} {times} {word}</em></span>')
    elif a["slot"] == "pass":
        out.append('<span class="uses none">работает всегда</span>')
    else:
        out.append('<span class="uses none">без ограничений</span>')
    out.append("</div>")
    out.append(f'<p>{a["text"]}</p>')
    if a.get("special") == "psy_fumble":
        out.append('<button class="act act--warn" data-act="psy-fumble">'
                   'Крит-провал: списать 3 монеты</button>')
    if a.get("special") == "taint_plus":
        out.append('<button class="act" data-act="taint-plus">Добавить команде 1 порчу</button>')
    if a.get("special") == "taint_minus":
        out.append('<button class="act" data-act="taint-minus">Снять 1 порчу</button>')
    out.append("</div>")
    return "\n        ".join(out)


